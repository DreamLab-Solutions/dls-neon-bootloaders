#!/usr/bin/env python3
"""Build native GRUB assets; no host boot configuration is touched."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
YELLOW = "#D9FF00"
PROFILES = {
    "720p": (20, 14, 38, 8),
    "1080p": (26, 18, 52, 12),
    "1440p": (36, 24, 68, 16),
    "4k": (52, 36, 104, 24),
}


def box(directory, name, color, fill):
    """Nine-slice native UI geometry, separate from the wallpaper."""
    im = Image.new("RGBA", (24, 24), fill)
    ImageDraw.Draw(im).rectangle((0, 0, 23, 23), outline=color, width=2)
    for key, rect in {
        "nw": (0, 0, 8, 8), "n": (8, 0, 16, 8), "ne": (16, 0, 24, 8),
        "w": (0, 8, 8, 16), "c": (8, 8, 16, 16), "e": (16, 8, 24, 16),
        "sw": (0, 16, 8, 24), "s": (8, 16, 16, 24), "se": (16, 16, 24, 24),
    }.items():
        im.crop(rect).save(directory / f"{name}_{key}.png")


def theme(font, small, row, spacing):
    return f'''# Generated by scripts/build.py — edit the source, then rebuild.
title-text: ""
desktop-image: "background.png"
desktop-image-scale-method: "stretch"
desktop-color: "#020807"
terminal-font: "DejaVu Sans Mono Regular {small}"
terminal-box: "terminal_*.png"
terminal-left: "5%"
terminal-top: "24%"
terminal-width: "90%"
terminal-height: "65%"
terminal-border: "12"

+ boot_menu {{
  left = 5%
  top = 27%
  width = 43%
  height = 43%
  item_font = "DejaVu Sans Mono Regular {font}"
  selected_item_font = "DejaVu Sans Mono Regular {font}"
  item_color = "#E7F2EE"
  selected_item_color = "{YELLOW}"
  item_height = {row}
  item_padding = 12
  item_spacing = {spacing}
  icon_width = 0
  icon_height = 0
  item_icon_space = 0
  selected_item_pixmap_style = "select_*.png"
  scrollbar = true
  scrollbar_width = 4
  scrollbar_frame = "scrollframe_*.png"
  scrollbar_thumb = "scrollthumb_*.png"
}}

+ label {{
  left = 5%
  top = 72%
  width = 60%
  height = {small + 10}
  id = "__timeout__"
  text = "Avvio tra %d secondi"
  font = "DejaVu Sans Mono Regular {small}"
  color = "#D9FF00"
}}

+ label {{
  left = 25%
  top = 94%
  width = 50%
  align = "center"
  text = "↑ ↓  Select     Enter  Boot     E  Edit     C  Console"
  font = "DejaVu Sans Mono Regular {small}"
  color = "#B5CEC8"
}}
'''


def main():
    out = ROOT / "build/theme"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    shutil.copy2(ROOT / "assets/backgrounds/portal.png", out / "background.png")
    shutil.copy2(ROOT / "assets/fonts/LICENSE-DejaVu.txt", out / "LICENSE-DejaVu.txt")
    for size in sorted({v for p in PROFILES.values() for v in p[:2]}):
        subprocess.run([
            "grub-mkfont", "-s", str(size), "-o", str(out / f"dejavu-{size}.pf2"),
            str(ROOT / "assets/fonts/DejaVuSansMono.ttf"),
        ], check=True)
    box(out, "select", YELLOW, (2, 8, 7, 225))
    box(out, "terminal", "#00B89C", (2, 8, 7, 255))
    box(out, "scrollframe", "#12342F", (2, 8, 7, 220))
    box(out, "scrollthumb", "#D9FF00", (217, 255, 0, 255))
    for profile, parameters in PROFILES.items():
        (out / f"theme-{profile}.txt").write_text(theme(*parameters))
    shutil.copy2(out / "theme-1080p.txt", out / "theme.txt")
    manifest = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                for p in sorted(out.iterdir()) if p.is_file()}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Built {len(manifest)} assets: {out}")


if __name__ == "__main__":
    main()
